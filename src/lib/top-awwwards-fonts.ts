// Stats
export function getTopAwwwardsStats() {
  const unique = new Map<string, FontInfo>();
  for (const font of TOP_AWWWARDS_FONTS) {
    if (!unique.has(font.family)) unique.set(font.family, font);
  }
  return {
    total: unique.size,
    google: Array.from(unique.values()).filter((f) => f.source === "google").length,
    fontshare: Array.from(unique.values()).filter((f) => f.source === "fontshare").length,
  };
}

// Get unique fonts (sem duplicados)
export function getTopAwwwardsFonts(): FontInfo[] {
  const unique = new Map<string, FontInfo>();
  for (const font of TOP_AWWWARDS_FONTS) {
    if (!unique.has(font.family)) unique.set(font.family, font);
  }
  return Array.from(unique.values());
}
